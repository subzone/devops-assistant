#!/usr/bin/env node
// Builds hooks/steve-frames.js, Steve's frames for the pane backdrop, from
// the Steve Trash export (four 896x1200 PNGs with alpha, same framing).
//
//   node scripts/steve-frames.mjs <export dir> [preview.png]
//
// Needs ffmpeg. Talking and blink frames are composited at full size:
// happy's mouth onto neutral (open, and squashed for half-open), and closed
// lids drawn over neutral's eyes. Each frame is cropped to head and
// shoulders, shrunk to W x H and stored as one byte per pixel: 0-254 light
// (perceptual), 255 transparent. The pane tints it with one hue.

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const [dir, previewPath] = process.argv.slice(2)
if (!dir) {
  console.error('usage: node scripts/steve-frames.mjs <export dir> [preview.png]')
  process.exit(2)
}

const SW = 896
const SH = 1200
const CROP = { x: 110, y: 30, w: 680, h: 800 }
const W = 160
const H = Math.round((W * CROP.h) / CROP.w)

/** @param {string} name */
function load(name) {
  const buf = execFileSync('ffmpeg', ['-loglevel', 'error', '-i', join(dir, `steve-trash-${name}.png`), '-f', 'rawvideo', '-pix_fmt', 'rgba', '-'], { maxBuffer: 64 << 20 })
  if (buf.length !== SW * SH * 4) throw new Error(`${name}: expected ${SW}x${SH} RGBA`)
  return new Uint8ClampedArray(buf)
}

const neutral = load('neutral')
const happy = load('happy')
const deadpan = load('deadpan')
const facepalm = load('facepalm')

/** Happy's mouth onto neutral; squash < 1 opens it less. */
function mouth(squash) {
  const out = neutral.slice()
  const box = { x0: 330, x1: 500, y0: 452, y1: 540 }
  const cy = 476
  const feather = 10
  for (let y = box.y0; y < box.y1; y++) {
    for (let x = box.x0; x < box.x1; x++) {
      const sy = Math.round(cy + (y - cy) / squash)
      if (sy < box.y0 || sy >= box.y1) continue
      const edge = Math.min(x - box.x0, box.x1 - 1 - x, y - box.y0, box.y1 - 1 - y)
      const k = Math.min(1, edge / feather)
      const o = (y * SW + x) * 4
      const s = (sy * SW + x) * 4
      for (let c = 0; c < 4; c++) out[o + c] = out[o + c] * (1 - k) + happy[s + c] * k
    }
  }
  return out
}

/** Neutral with closed lids: the eyes filled with skin, a lash line across. */
function blink() {
  const out = neutral.slice()
  const skin = [...neutral.slice((420 * SW + 330) * 4, (420 * SW + 330) * 4 + 3)]
  for (const [cx, cy] of [
    [346, 358],
    [466, 356],
  ]) {
    const rx = 54
    const ry = 38
    for (let y = cy - ry; y <= cy + ry; y++) {
      for (let x = cx - rx; x <= cx + rx; x++) {
        const d = ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2
        if (d > 1) continue
        const o = (y * SW + x) * 4
        // the lid line, curving down a little at the middle
        const line = cy + 6 + 6 * (1 - ((x - cx) / rx) ** 2)
        const ink = Math.abs(y - line) < 4.5
        out[o] = ink ? 20 : skin[0]
        out[o + 1] = ink ? 16 : skin[1]
        out[o + 2] = ink ? 16 : skin[2]
        out[o + 3] = 255
      }
    }
  }
  return out
}

const frames = {
  idle: neutral,
  blink: blink(),
  talk1: mouth(0.5),
  talk2: mouth(1),
  think: deadpan,
  yay: happy,
  oops: facepalm,
}

/** Crop, shrink (area average, alpha-weighted), to light bytes. */
function shrink(rgba) {
  const out = new Uint8Array(W * H)
  const fx = CROP.w / W
  const fy = CROP.h / H
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      let a = 0
      let l = 0
      let n = 0
      for (let sy = Math.floor(CROP.y + y * fy); sy < Math.floor(CROP.y + (y + 1) * fy); sy++) {
        for (let sx = Math.floor(CROP.x + x * fx); sx < Math.floor(CROP.x + (x + 1) * fx); sx++) {
          const o = (sy * SW + sx) * 4
          const al = rgba[o + 3] / 255
          // linear light, then back to perceptual
          const lin = 0.2126 * (rgba[o] / 255) ** 2.2 + 0.7152 * (rgba[o + 1] / 255) ** 2.2 + 0.0722 * (rgba[o + 2] / 255) ** 2.2
          l += lin * al
          a += al
          n++
        }
      }
      out[y * W + x] = a / n < 0.5 ? 255 : Math.min(254, Math.round((l / a) ** (1 / 2.2) * 254))
    }
  }
  return out
}

const packed = Object.fromEntries(Object.entries(frames).map(([k, v]) => [k, Buffer.from(shrink(v)).toString('base64')]))
const here = dirname(fileURLToPath(import.meta.url))
const target = join(here, '..', 'hooks', 'steve-frames.js')
writeFileSync(
  target,
  `// Generated by scripts/steve-frames.mjs from the Steve Trash export. Do not edit.\n` +
    `// ${W}x${H}, one byte per pixel: 0-254 light, 255 transparent; base64.\n` +
    `export const STEVE_W = ${W}\nexport const STEVE_H = ${H}\n` +
    `/** @type {Record<'idle' | 'blink' | 'talk1' | 'talk2' | 'think' | 'yay' | 'oops', string>} */\n` +
    `export const STEVE_FRAMES = ${JSON.stringify(packed, null, 2)}\n`,
)
console.log(`wrote ${target} (${W}x${H}, ${Object.keys(packed).length} frames)`)

if (previewPath) {
  // Every frame side by side, as the pane tints it, 4x.
  const { tint } = await import(join(here, '..', 'hooks', 'steve.js'))
  const names = Object.keys(frames)
  const PW = W * names.length
  const img = Buffer.alloc(PW * H * 3)
  names.forEach((name, i) => {
    const px = shrink(frames[name])
    for (let y = 0; y < H; y++)
      for (let x = 0; x < W; x++) {
        const v = px[y * W + x]
        const c = v === 255 ? 0x000000 : tint(v)
        const o = (y * PW + i * W + x) * 3
        img[o] = c >> 16
        img[o + 1] = (c >> 8) & 255
        img[o + 2] = c & 255
      }
  })
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-s', `${PW}x${H}`, '-i', '-', '-vf', 'scale=iw*4:ih*4:flags=neighbor', previewPath], { input: img })
  console.log(`preview ${previewPath}`)
}
